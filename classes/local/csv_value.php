namespace tool_upgradeguard\local;

/**
 * Makes untrusted text safe for spreadsheet CSV imports.
 */
final class csv_value {
    /**
     * Prevent spreadsheet software interpreting a cell as a formula.
     *
     * @param string $value The value to export.
     * @return string A safe CSV cell value.
     */
    public static function neutralise(string $value): string {
        if ($value !== '' && in_array($value[0], ['=', '+', '-', '@'], true)) {
            return "'" . $value;
        }

        return $value;
    }
}
